export function serveGlyph(theme: ThemeId): string {
  switch (theme) {
    case 'wimbledon':
      return '▸'
    case 'rolandGarros':
      return '//'
    case 'usOpen':
      return '●'
    case 'australianOpen':
      return '▶'
    default:
      return '●'
  }
}

