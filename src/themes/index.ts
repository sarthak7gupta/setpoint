/** Resolves the complete CSS variable mapping for any (style, slam) pair. */
export function getThemeVars(
  theme: ThemeId,
  style: DesignStyleId = 'classic',
): Record<string, string> {
  const byStyle = styleSlamMatrix[style] ?? styleSlamMatrix.classic
  const vars = { ...(byStyle[theme] ?? themes[theme]) }
  const surfaces = ['--bg-deep', '--bg-mid', '--bg-elevated']
    .map((k) => vars[k])
    .filter((v) => /^#[0-9a-f]{6}$/i.test(v))
  vars['--text-muted'] = ensureContrast(vars['--text-muted'], surfaces)
  for (const [name, start, end] of [
    ['primary', vars['--purple-bright'], vars['--purple']],
    ['accent', vars['--accent'], vars['--green-bright']],
  ]) {
    const colors = readableGradient(start, end)
    vars[`--button-${name}-start`] = colors.start
    vars[`--button-${name}-end`] = colors.end
    vars[`--button-${name}-text`] = colors.text
  }
  return vars
}
